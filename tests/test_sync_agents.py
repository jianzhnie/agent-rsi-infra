"""Regression tests for keeping generated role adapters in sync."""

import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class AgentAdapterSyncTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.project = Path(self.temp.name)
        scripts = self.project / "scripts"
        scripts.mkdir()
        shutil.copyfile(ROOT / "scripts/sync_agents.py", scripts / "sync_agents.py")
        self.source_dir = self.project / ".agents/agents"
        self.source_dir.mkdir(parents=True)
        self.source = self.source_dir / "sample-role.md"
        self.source.write_text(
            "---\nname: sample-role\ndescription: Sample role\n---\n\nRole instructions.\n"
        )
        self.claude_dir = self.project / ".claude/agents"
        self.codex_dir = self.project / ".codex/agents"
        self.manual = self.claude_dir / "local.md"
        self.manual.parent.mkdir(parents=True)
        self.manual.write_text("# Manually maintained adapter\n")
        self.codex_dir.mkdir(parents=True)

    def run_sync(self, *args):
        return subprocess.run(
            [sys.executable, str(self.project / "scripts/sync_agents.py"), *args],
            cwd=self.project,
            capture_output=True,
            text=True,
            timeout=10,
        )

    def test_check_reports_removed_role_adapters_without_deleting(self) -> None:
        self.assertEqual(self.run_sync().returncode, 0)
        generated = [
            self.claude_dir / "sample-role.md",
            self.codex_dir / "sample-role.toml",
        ]
        for path in generated:
            self.assertTrue(path.is_file())
        self.source.unlink()

        result = self.run_sync("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn(".claude/agents/sample-role.md", result.stderr)
        self.assertIn(".codex/agents/sample-role.toml", result.stderr)
        self.assertTrue(all(path.is_file() for path in generated))
        self.assertTrue(self.manual.is_file())

    def test_sync_removes_only_generator_owned_orphan_files(self) -> None:
        self.assertEqual(self.run_sync().returncode, 0)
        self.source.unlink()

        result = self.run_sync()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse((self.claude_dir / "sample-role.md").exists())
        self.assertFalse((self.codex_dir / "sample-role.toml").exists())
        self.assertTrue(self.manual.is_file())
        self.assertEqual(
            (self.project / ".codex/config.toml").read_text(),
            "# Generated by scripts/sync_agents.py; do not edit.\n",
        )


if __name__ == "__main__":
    unittest.main()

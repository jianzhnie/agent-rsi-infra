"""Task-specific quality checks for trusted RSIBench-Infra verifier outputs.

These functions validate measurements generated by an independent verifier;
they do not execute benchmark datasets or attest the origin of the evidence.
"""
from __future__ import annotations

import math
from typing import Any


def _metric(value: Any, name: str) -> float:
    if type(value) not in (int, float) or not math.isfinite(value):
        raise ValueError(f"{name} must be finite numeric data")
    return float(value)


def _range(name: str, value: Any, low: float | None = None,
           high: float | None = None) -> dict[str, Any]:
    number = _metric(value, name)
    return {"metric": name, "value": number,
            "passed": (low is None or number >= low) and (high is None or number <= high),
            "minimum": low, "maximum": high}


def _accuracy(value: Any) -> float:
    value = _metric(value, "accuracy")
    if not 0 <= value <= 1:
        raise ValueError("accuracy must be in [0, 1]")
    return value


def _relative(candidate: Any, reference: Any, name: str) -> float:
    candidate = _metric(candidate, f"{name}.candidate")
    reference = _metric(reference, f"{name}.reference")
    if reference == 0:
        return 0.0 if candidate == 0 else math.inf
    return abs(candidate - reference) / abs(reference)


def evaluate_quality(gate_id: str, evidence: dict[str, Any],
                     acceptance_accuracy: float | None = None) -> dict[str, Any]:
    if not isinstance(evidence, dict):
        raise ValueError("Quality evidence must be a JSON object")
    checks: list[dict[str, Any]] = []
    if gate_id.startswith("longbench_v2_"):
        expected = 36 if gate_id == "longbench_v2_36q_24k" else 100
        if type(evidence.get("question_count")) is not int or evidence["question_count"] != expected:
            raise ValueError(f"LongBench gate requires exactly {expected} fixed questions")
        if acceptance_accuracy is None:
            raise ValueError("Provide independent baseline-calibrated acceptance_accuracy")
        threshold = _accuracy(acceptance_accuracy)
        checks.append(_range("accuracy", _accuracy(evidence.get("accuracy")), threshold, 1.0))
    elif gate_id in ("gsm8k_088", "gsm8k_0865"):
        minimum = 0.88 if gate_id == "gsm8k_088" else 0.865
        checks.append(_range("accuracy", _accuracy(evidence.get("accuracy")), minimum, 1.0))
    elif gate_id == "mmmu_qwen3vl":
        accuracy = _accuracy(evidence.get("accuracy"))
        if type(evidence.get("example_count")) is not int or evidence["example_count"] != 847:
            raise ValueError("MMMU gate requires all 847 validation examples")
        checks.append(_range("absolute_accuracy_deviation", abs(accuracy - 0.7273), 0, 0.05))
    elif gate_id == "wan22_video":
        cases = evidence.get("cases")
        if not isinstance(cases, list) or len(cases) != 4:
            raise ValueError("Wan2.2 requires all four frozen prompt-seed cases")
        limits = {
            "mean_framewise_lpips": (0, 0.25834550),
            "worst_frame_lpips": (0, 0.31249873),
            "mean_temporal_difference_mae": (0, 0.05224669),
            "worst_pair_temporal_difference_mae": (0, 0.14031570),
            "motion_magnitude_ratio": (0.97985323, 1.04997272),
            "absolute_duration_error_seconds": (0, 0.001),
            "absolute_frame_timestamp_error_seconds": (0, 0.0001),
        }
        for i, case in enumerate(cases):
            if not isinstance(case, dict):
                raise ValueError("Wan2.2 case must be an object")
            for name in ("video_dimensions_match", "video_frame_count_match", "video_frame_rate_match",
                         "video_encoding_valid", "timestamps_valid"):
                checks.append({"metric": name, "case": i, "passed": case.get(name) is True})
            for name, (low, high) in limits.items():
                check = _range(name, case.get(name), low, high)
                check["case"] = i
                checks.append(check)
    elif gate_id == "minimax_h3_video_audio":
        limits = {
            "mean_video_lpips": (0, 0.2),
            "audio_spectral_cosine_similarity": (0.8, 1.0),
            "audio_rms_amplitude_ratio": (0.5, 2.0),
        }
        for name in ("video_dimensions_match", "video_frame_count_match", "video_frame_rate_match", "video_encoding_valid"):
            checks.append({"metric": name, "passed": evidence.get(name) is True})
        for name, (low, high) in limits.items():
            checks.append(_range(name, evidence.get(name), low, high))
        for name in ("audio_sample_rate_matches", "audio_channels_match", "audio_format_valid"):
            checks.append({"metric": name, "passed": evidence.get(name) is True})
    elif gate_id == "lingbot_world_frames":
        chunks = evidence.get("chunks")
        if evidence.get("chunk_count") != 16 or evidence.get("total_frames") != 189:
            raise ValueError("LingBot gate requires 16 chunks and 189 frames")
        if not isinstance(chunks, list) or len(chunks) != 16:
            raise ValueError("LingBot must report each of the 16 chunks")
        for i, chunk in enumerate(chunks):
            if not isinstance(chunk, dict):
                raise ValueError("LingBot chunk must be an object")
            checks.extend([
                {"metric": "frame_count_matches", "case": i, "passed": chunk.get("frame_count_matches") is True},
                {"metric": "frame_shape_matches", "case": i, "passed": chunk.get("frame_shape_matches") is True},
                {"metric": "event_id_matches", "case": i, "passed": chunk.get("event_id_matches") is True},
                {**_range("mean_absolute_pixel_error", chunk.get("mean_absolute_pixel_error"), 0, 2), "case": i},
                {**_range("psnr_db", chunk.get("psnr_db"), 35, None), "case": i},
            ])
    elif gate_id == "pi05_reference_actions":
        cases = evidence.get("cases")
        if not isinstance(cases, list) or len(cases) != 16:
            raise ValueError("pi0.5 gate requires 16 frozen reference observations")
        for i, case in enumerate(cases):
            if not isinstance(case, dict):
                raise ValueError("Action case must be an object")
            checks.append({"metric": "action_shape_matches", "case": i, "passed": case.get("action_shape_matches") is True})
            for name, field, limit in (
                ("max_absolute_action_error", "max_absolute_error", 0.05),
                ("mean_absolute_action_error", "mean_absolute_error", 0.01),
            ):
                check = _range(name, case.get(field), 0, limit)
                check["case"] = i
                checks.append(check)
    elif gate_id == "qwen3_tts_wer":
        if evidence.get("completed_requests") != 202 or evidence.get("all_audio_valid") is not True:
            raise ValueError("TTS gate requires all 202 valid fixed requests")
        checks.append(_range("mean_wer", evidence.get("mean_wer"), 0, 0.014))
    elif gate_id in ("training_curve_64", "training_curve_16", "training_curve_8"):
        updates_expected = {"training_curve_64": 64, "training_curve_16": 16, "training_curve_8": 8}[gate_id]
        updates = evidence.get("updates")
        if not isinstance(updates, list) or len(updates) != updates_expected:
            raise ValueError(f"Training gate requires exactly {updates_expected} ordered updates")
        if evidence.get("admission_checks_passed") is not True:
            raise ValueError("Training replay admission, identity and negative controls must pass")
        for i, update in enumerate(updates):
            if (update.get("update_index") != i or update.get("finite") is not True
                    or update.get("masks_match") is not True
                    or update.get("input_count_matches") is not True
                    or update.get("optimizer_update_count_matches") is not True):
                raise ValueError(f"Training update {i} is missing, invalid, reordered or changed its workload contract")
            for candidate, reference, label, limit in (
                ("candidate_loss", "reference_loss", "relative_loss_error", 0.02),
                ("candidate_global_grad_norm", "reference_global_grad_norm", "relative_grad_norm_error", 0.15),
            ):
                error = _relative(update.get(candidate), update.get(reference), label)
                check = {"metric": label, "value": error if math.isfinite(error) else "infinite",
                         "passed": error < limit, "strict_limit": limit, "update": i}
                checks.append(check)
    elif gate_id == "vl_grpo_curve":
        updates = evidence.get("updates")
        if not isinstance(updates, list) or len(updates) != 8:
            raise ValueError("VLM GRPO gate requires eight ordered updates")
        if evidence.get("admission_checks_passed") is not True:
            raise ValueError("VLM GRPO admission, identity and negative controls must pass")
        for i, update in enumerate(updates):
            if (update.get("update_index") != i or update.get("finite") is not True
                    or update.get("masks_match") is not True
                    or update.get("input_count_matches") is not True
                    or update.get("optimizer_update_count_matches") is not True):
                raise ValueError(f"VLM GRPO update {i} is missing, invalid, reordered or changed its workload contract")
        families = {
            "total_loss": (0.002, 0.02, 0.01),
            "gradient_norm": (4.0, 0.10, 0.1),
            "policy_loss": (0.002, 0.02, 0.01),
            "kl_loss": (0.0003, 0.20, 0.0),
            "kl_gradient_probe": (0.002, 0.05, 0.0),
        }
        states = []
        for i, update in enumerate(updates):
            for name, (a, b, c) in families.items():
                if name == "kl_gradient_probe":
                    if i != 0:
                        continue
                    source = evidence.get(name)
                else:
                    source = update.get(name)
                if not isinstance(source, dict):
                    raise ValueError(f"Missing normalized-error inputs for {name}")
                cand, ref = source.get("candidate"), source.get("reference")
                if not isinstance(cand, list) or not isinstance(ref, list) or not cand or len(cand) != len(ref):
                    raise ValueError(f"{name} requires equal nonempty candidate/reference arrays")
                errors = [_metric(abs(x-y), "absolute error") / (a + b * max(abs(_metric(y, "reference")), c))
                          for x, y in zip(cand, ref, strict=True)]
                error = max(errors)
                state = "passed" if error <= 0.5 else "failed" if error >= 1 else "inconclusive"
                checks.append({"metric": name, "update": i if name != "kl_gradient_probe" else "final",
                               "normalized_error": error, "status": state})
                states.append(state)
            for name, passed, failed in (
                ("actor_forward_error", 6.0, 8.0),
                ("reference_forward_error", 0.6, 0.9),
            ):
                value = _metric(update.get(name), name)
                state = "passed" if value <= passed else "failed" if value >= failed else "inconclusive"
                checks.append({"metric": name, "update": i, "value": value, "status": state})
                states.append(state)
        overall = "failed" if "failed" in states else "inconclusive" if "inconclusive" in states else "passed"
        return {"status": overall, "passed": overall == "passed", "checks": checks}
    else:
        raise ValueError(f"Unknown quality gate: {gate_id}")
    passed = all(row.get("passed") is True for row in checks)
    return {"status": "passed" if passed else "failed", "passed": passed, "checks": checks}

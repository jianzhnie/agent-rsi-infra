"""Generate client role adapters from shared Markdown definitions."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(root: Path = ROOT) -> dict[Path, str]:
    outputs = {}
    config = ["# Generated by scripts/sync_agents.py; do not edit.\n"]
    for source in sorted((root / ".agents/roles").glob("*.md")):
        _, header, body = source.read_text().split("---", 2)
        name_match = re.search(r"^name: (.+)$", header, re.M)
        description_match = re.search(r"^description: (.+)$", header, re.M)
        if not name_match or not description_match:
            raise ValueError(f"Missing role name or description: {source}")
        name = name_match.group(1)
        description = description_match.group(1)
        if name != source.stem or not re.fullmatch(r"[a-z0-9-]+", name):
            raise ValueError(f"Invalid role name: {source}")
        # Both adapter directories have the same depth as the source directory.
        body = body.strip()
        tools = "Read, Bash, Grep, Glob"
        if name == "debugger":
            tools += ", Edit"
        outputs[root / ".claude/agents" / source.name] = (
            f"---\nname: {name}\ndescription: {json.dumps(description, ensure_ascii=False)}\ntools: {tools}\n---\n\n"
            "<!-- Generated by scripts/sync_agents.py; edit .agents/roles instead. -->\n\n"
            + body
            + "\n"
        )
        instructions = (
            "遵循目标仓库指令。角色定义不授予额外权限或自动委派权限。\n\n" + body
        )
        outputs[root / ".codex/agents" / f"{name}.toml"] = (
            "# Generated by scripts/sync_agents.py; do not edit.\n"
            + ('sandbox_mode = "read-only"\n' if name == "performance-analyzer" else "")
            + "developer_instructions = "
            + json.dumps(instructions, ensure_ascii=False)
            + "\n"
        )
        config.append(
            f"[agents.{name}]\ndescription = {json.dumps(description, ensure_ascii=False)}\n"
            f'config_file = "agents/{name}.toml"\n'
        )
    outputs[root / ".codex/config.toml"] = "\n".join(config)
    return outputs


def _obsolete_outputs(outputs: dict[Path, str], root: Path = ROOT) -> list[Path]:
    """Find generator-owned adapters whose source role no longer exists."""
    expected = set(outputs)
    obsolete = []
    generated_markers = (
        "<!-- Generated by scripts/sync_agents.py; edit .agents/roles instead. -->",
        "# Generated by scripts/sync_agents.py; do not edit.",
    )
    for directory, pattern in (
        (root / ".claude/agents", "*.md"),
        (root / ".codex/agents", "*.toml"),
    ):
        for path in directory.glob(pattern):
            if path in expected:
                continue
            try:
                generated = any(
                    marker in path.read_text(encoding="utf-8")[:1000]
                    for marker in generated_markers
                )
            except OSError:
                generated = False
            if generated:
                obsolete.append(path)
    return sorted(obsolete)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Detect stale adapters")
    args = parser.parse_args()
    outputs = render()
    obsolete = _obsolete_outputs(outputs)
    stale = [str(path.relative_to(ROOT)) for path in obsolete]
    for path, content in outputs.items():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if not args.check:
        for path in obsolete:
            path.unlink()
    if args.check and stale:
        parser.exit(1, "Stale agent adapters: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
